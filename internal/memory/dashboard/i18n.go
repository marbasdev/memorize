func uiText(lang, key string) string {
	l := normalizeLang(lang)
	if m := uiTranslations[l]; m != nil {
		if v, ok := m[key]; ok {
			return v
		}
	}
	if v, ok := uiTranslations["en"][key]; ok {
		return v
	}
	return key
}
